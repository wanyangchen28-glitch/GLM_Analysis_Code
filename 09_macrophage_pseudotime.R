library(Seurat)
library(monocle)
library(Biobase)

mac <- readRDS("final_macrophages.rds")
atlas <- readRDS("pyroptosis_scored_single_cell.rds")
mac$pyroptosis_score <- atlas$pyroptosis_score[match(colnames(mac), colnames(atlas))]
mac <- NormalizeData(mac, normalization.method = "LogNormalize", scale.factor = 10000)
mac <- FindVariableFeatures(mac, selection.method = "vst", nfeatures = 1500)
counts <- LayerData(mac, assay = "RNA", layer = "counts")
features <- data.frame(gene_short_name = rownames(counts), row.names = rownames(counts))
cds <- newCellDataSet(counts, phenoData = AnnotatedDataFrame(mac[[]]), featureData = AnnotatedDataFrame(features), lowerDetectionLimit = 0.5, expressionFamily = negbinomial.size())
cds <- estimateSizeFactors(cds)
cds <- estimateDispersions(cds)
cds <- setOrderingFilter(cds, VariableFeatures(mac))
set.seed(1234)
cds <- reduceDimension(cds, max_components = 2, method = "DDRTree", ncenter = 30)
cds <- orderCells(cds)
cds <- orderCells(cds, root_state = 7)
inflammatory_genes <- readLines("gene_sets/inflammatory_response_genes.txt")
mac$inflammatory_score <- score_signature(mac, inflammatory_genes)[colnames(mac)]
meta <- pData(cds)
expr <- LayerData(mac, assay = "RNA", layer = "data")
meta$CASP1 <- as.numeric(expr["CASP1", rownames(meta)])
meta$IL18 <- as.numeric(expr["IL18", rownames(meta)])
meta$inflammatory_score <- mac$inflammatory_score[match(rownames(meta), colnames(mac))]
meta$inflammatory_high <- meta$inflammatory_score > median(meta$inflammatory_score)
proportion <- aggregate(inflammatory_high ~ State, meta, mean)
write.csv(meta, "macrophage_pseudotime_data.csv")
write.csv(proportion, "inflammatory_high_fraction_by_state.csv", row.names = FALSE)
saveRDS(cds, "monocle2_trajectory.rds")
